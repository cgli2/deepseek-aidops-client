#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_migrated_tables_are_data_not_mechanism() {
        // 这些表被保留下来只是为了冷启动过渡；机制层（target_extract）不得引用它们。
        let mechanism = include_str!("target_extract.rs");
        let mechanism = mechanism.split("#[cfg(test)]").next().unwrap_or(mechanism);
        assert!(!mechanism.contains("builtin_profile::"));
    }

    #[test]
    fn tables_are_non_empty_and_deduplicated() {
        assert!(!CJK_NOUN_MARKERS.is_empty());
        assert!(!CJK_ACTION_TAILS.is_empty());
        assert!(!CJK_LEAD_STOPWORDS.is_empty());
    }
}
